static void OLED_SendCommand(u8 command)
{
	TWI_SendStartCondition();
	TWI_SendSlaveAddressWithWrite(OLED_ADDRESS);
	TWI_WriteDataByte(0x00);
	TWI_WriteDataByte(command);
	TWI_SendStopCondition();
}

void OLED_Init(void)
{
	_delay_ms(100);

	OLED_SendCommand(0xAE);
	OLED_SendCommand(0xD5); OLED_SendCommand(0x80);
	OLED_SendCommand(0xA8); OLED_SendCommand(0x3F);
	OLED_SendCommand(0xD3); OLED_SendCommand(0x00);
	OLED_SendCommand(0x40);
	OLED_SendCommand(0x8D); OLED_SendCommand(0x14);
	OLED_SendCommand(0x20); OLED_SendCommand(0x02);   /* Page mode */
	OLED_SendCommand(0xA1);
	OLED_SendCommand(0xC8);
	OLED_SendCommand(0xDA); OLED_SendCommand(0x12);
	OLED_SendCommand(0x81); OLED_SendCommand(0xCF);
	OLED_SendCommand(0xD9); OLED_SendCommand(0xF1);
	OLED_SendCommand(0xDB); OLED_SendCommand(0x40);
	OLED_SendCommand(0xA4);
	OLED_SendCommand(0xA6);
	OLED_SendCommand(0xAF);

	OLED_Clear();
}

void OLED_SetCursor(u8 row, u8 column)
{
	OLED_SendCommand(0xB0 + row);
	OLED_SendCommand(0x00 + (column & 0x0F));
	OLED_SendCommand(0x10 + (column >> 4));
}

void OLED_Clear(void)
{
	u8 page;
	u8 column;

	for(page = 0; page < 8; page++)
	{
		OLED_SetCursor(page, 0);

		TWI_SendStartCondition();
		TWI_SendSlaveAddressWithWrite(OLED_ADDRESS);
		TWI_WriteDataByte(0x40);
		for(column = 0; column < 128; column++)
		{
			TWI_WriteDataByte(0x00);
		}
		TWI_SendStopCondition();
	}
}

void OLED_WriteChar(u8 data)
{
	u8 i;

	if(data < 32 || data > 122)
	{
		data = ' ';
	}

	TWI_SendStartCondition();
	TWI_SendSlaveAddressWithWrite(OLED_ADDRESS);
	TWI_WriteDataByte(0x40);
	for(i = 0; i < 5; i++)
	{
		TWI_WriteDataByte(Font[data - 32][i]);
	}
	TWI_WriteDataByte(0x00);
	TWI_SendStopCondition();
}

void OLED_WriteString(char *str)
{
	while(*str != '\0')
	{
		OLED_WriteChar(*str);
		str++;
	}
}